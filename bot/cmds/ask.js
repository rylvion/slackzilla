const { log } = require("../utils/logger")
const { answerQuestion, listCommands } = require("../../server/lib/rag/rag")

const ANONYMOUS_MODE = false

function getHelp() {
    return (
        "🤖 *Slackzilla AI help*\n" +
        "> *Usage:*\n" +
        "> `/sz-ask <question>` - asks Slackzilla AI a question\n" +
        "> `/sz-ask help` - shows this help message\n" +
        "> *Examples:*\n" +
        "> `/sz-ask how do I hash some text?`\n" +
        "> `/sz-ask what does /sz-roll do?`\n" +
        "> `/sz-ask what is Slackzilla?`\n"
    )
}

function getUsage(result, activities) {
    if (result?.usage) return result.usage

    const completedActivity = [...activities].reverse().find(activity =>
        activity.type === "ai" && activity.status === "completed" && activity.metadata
    )

    return {
        input: completedActivity?.metadata?.inputTokens,
        output: completedActivity?.metadata?.outputTokens,
        total: completedActivity?.metadata?.totalTokens
    }
}


module.exports = (app, meta) => {
    app.command(meta.cmd, async ({ ack, respond, command }) => {
        await ack()

        const question = command.text?.trim()

        if (!question || question.toLowerCase() === "help") {
            await respond(getHelp())
            return
        }

        try {
            await respond("🤔 Thinking...")
            const requestedCommand = question.match(/(?:run|execute)\s+(\/sz-[\w-]+)(?:\s+(.+))?$/i)
            const requestedCommandMeta = requestedCommand && listCommands().find(item => item.cmd.toLowerCase() === requestedCommand[1].toLowerCase())
            const result = await answerQuestion({
                question,
                commandId: requestedCommandMeta?.id,
                commandText: requestedCommand?.[2],
                identity: {
                    userId: command.user_id,
                    username: command.user_name,
                    channelId: command.channel_id
                }
            })

            result.answer += "\n\n> *Note:* This answer was generated by Slackzilla AI. It may not be accurate or complete. Please verify any information before acting on it."

            const usage = getUsage(result, result.activities)

            result.answer += `\n\n> *Usage:* ${usage?.input ?? 0} input tokens, ${usage?.output ?? 0} output tokens, ${usage?.total ?? 0} total tokens.`
            await respond(result.answer)


            if (ANONYMOUS_MODE) {
                log.info(result)
                log.success("{user} successfully executed {cmd} command with arguments: {0}, ", command, question || "(none)")
            } else {
                log.success("{user} successfully executed {cmd} command", command)
            }
        } catch (error) {
            log.error("{user} failed to execute {cmd}: {0}", command,error.message)
            await respond("❌ I couldn't get an answer right now. Please try again later.")
        }
    })
}